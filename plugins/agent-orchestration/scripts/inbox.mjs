// @ts-check
/**
 * LAYER 1 — `tasks/INBOX.md`: the single place collecting everything that needs a human
 * (docs/agent-orchestration.md §4). Three groups: planner questions · tasks/bugs
 * awaiting approval · merge conflicts.
 *
 * INBOX is a VIEW, regenerated every round — the source of truth is task front-matter,
 * bug files and question files `tasks/questions/Q-xxx-*.md`. Humans edit only the
 * answer line (`config.headings.answer` + `:`); everything else is overwritten on the next run.
 *
 * An answer the human just typed that the planner has not yet harvested into the question
 * file must NOT be lost on regeneration: the file layer reads the old INBOX with `parseAnswers`
 * and passes it to `buildInbox` via `pending`.
 */
import fs from "node:fs";
import path from "node:path";
import { loadBacklog, loadBugs, loadQuestions, section } from "./backlog.mjs";
import { evaluateGate } from "./gates.mjs";
import { config } from "./config.mjs";
import { loadFindings, RESOLUTIONS_FILE } from "./findings.mjs";
import { emitEvent } from "./events.mjs";
import { listWorktrees, orphanWorktrees, slotOfOwner } from "./worker.mjs";
import { MAX_SHOWN_PATHS, readDirtyTree, readSerialLeftover, unownedChanges } from "./store.mjs";
import { ciGateNow, ciInboxLines } from "./ci-status.mjs";

const ANSWER = `${config.headings.answer}:`;

/**
 * INBOX section titles that are also re-read (`inboxCounts`, the conductor's wait count).
 * Generated and parsed from these constants only — keep them in one place.
 */
export const INBOX_SECTIONS = Object.freeze({ questions: "Questions", approvals: "Awaiting approval" });

/**
 * @typedef {Object} Conflict  rebase conflict reported by the integrator (A-011)
 * @property {string} id       child task
 * @property {string[]} files
 */

/**
 * @param {{
 *   backlog: Map<string, import("./backlog.mjs").Task>,
 *   bugs: Map<string, import("./backlog.mjs").Bug>,
 *   questions: Map<string, import("./backlog.mjs").Question>,
 *   conflicts?: Conflict[],
 *   pending?: Map<string, string>,
 *   findings?: Pick<ReturnType<typeof loadFindings>, "findings" | "failures"> & Partial<ReturnType<typeof loadFindings>>,
 *   orphans?: string[],
 *   ci?: import("./ci-status.mjs").CiStatus|null,
 *   unowned?: string[],
 *   ciClosed?: {unpushed: number|null}|null,
 * }} input  `unowned` = uncommitted files on the main tree owned by no task (A-086) — the serial lane is waiting for a human;
 *           `ciClosed` = the CI gate is closed (A-084), with the number of unpushed commits
 * @returns {string} markdown — DETERMINISTIC: same input, same bytes
 */
export function buildInbox({ backlog, bugs, questions, conflicts = [], pending = new Map(), findings = { findings: [], failures: [] }, orphans = [], ci = null, unowned = [], ciClosed = null }) {
  const open = newestFirst([...questions.values()].filter((q) => q.status === "open"));
  const waitingTasks = newestFirst([...backlog.values()].filter((t) => t.status === "needs-human"));
  const waitingBugs = newestFirst([...bugs.values()].filter((b) => b.status === "needs-human"));
  const merges = [...conflicts].sort((a, b) => a.id.localeCompare(b.id));

  const out = [
    "# INBOX — needs a human",
    "",
    `> Generated by \`${config.cliHint} inbox\`. **Edit only the \`${ANSWER}\` lines** — everything else`,
    "> is overwritten on the next run. Sources: `tasks/questions/`, task front-matter and bug files.",
    "",
    ...ciInboxLines(ci, ciClosed, config.ci?.branch ?? "main", config.ci?.localHint ?? null),
    `## ${INBOX_SECTIONS.questions} (${open.length})`,
    "",
  ];

  if (open.length === 0) out.push("_No open questions._", "");
  for (const q of open) {
    out.push(`### ${q.id} · ${q.title}`, "");
    if (q.blocks.length > 0) out.push(`Blocks: ${q.blocks.join(", ")}`, "");
    for (const name of [config.headings.question, config.headings.options, config.headings.recommendation]) {
      const text = section(q.body, name);
      if (text !== "") out.push(`**${name}**`, "", text, "");
    }
    const answer = q.answer !== "" ? q.answer : (pending.get(q.id) ?? "");
    out.push(answer === "" ? ANSWER : `${ANSWER} ${answer}`, "");
  }

  const waiting = waitingTasks.length + waitingBugs.length + (unowned.length > 0 ? 1 : 0);
  out.push(`## ${INBOX_SECTIONS.approvals} (${waiting})`, "");
  if (waiting === 0) out.push("_Nothing awaiting approval._");
  if (unowned.length > 0) out.push(unownedLine(unowned));
  for (const t of waitingTasks) {
    const reason = evaluateGate(t).reason ?? "needs human review";
    out.push(`- **${t.id}** · ${t.title} — ${reason}`);
  }
  for (const b of waitingBugs) {
    out.push(`- **${b.id}** (bug of ${b.parent}, ${b.severity}) · ${b.title} — fix rounds exhausted`);
  }
  out.push("");

  // Notices, not questions: they do NOT block merging and need no answer line (A-021).
  const nFindings = findings.findings.length + findings.failures.length;
  // Only OPEN findings are counted and listed; findings matched by the resolutions ledger (A-071) get a single count line.
  out.push(`## Reviewer findings (${nFindings})`, "");
  const nClosed = findings.resolved?.length ?? 0;
  if (nClosed > 0) out.push(`Resolved: ${nClosed} — see \`${RESOLUTIONS_FILE}\``, "");
  if (nFindings === 0) out.push("_No findings._");
  for (const f of findings.failures) {
    if (f.task === RESOLUTIONS_FILE) out.push(`- ⚠ resolutions ledger \`${RESOLUTIONS_FILE}\` is broken, treated as empty — ${f.error}`);
    else out.push(`- **${f.task}** · ${f.role} · ⚠ reviewer failed to submit findings — ${f.error}`);
  }
  for (const f of findings.findings) {
    const where = f.line === undefined ? f.file : `${f.file}:${f.line}`;
    out.push(`- **${f.task}** · ${f.role} · ${f.severity} · ${f.rule} · \`${where}\` — ${f.detail}`);
  }
  out.push("");

  // Shown only when present (A-024): worker worktrees owned by no task — the conductor does NOT delete them.
  if (orphans.length > 0) {
    out.push(`## Orphan worktrees (${orphans.length})`, "");
    for (const id of orphans) out.push(`- **${id}** · \`.claude/worktrees/${id}\` — not owned by any active task; inspect, then clean up with \`worker rm ${id}\``);
    out.push("");
  }

  out.push(`## Merge conflicts (${merges.length})`, "");
  if (merges.length === 0) out.push("_No conflicts._");
  for (const c of merges) out.push(`- **${c.id}** · ${c.files.map((f) => `\`${f}\``).join(", ")}`);
  out.push("");

  return out.join("\n");
}

/**
 * One line for a dirty main tree with no known owner (A-086): file count + up to `MAX_SHOWN_PATHS` paths. PURE FUNCTION.
 * @param {string[]} files @returns {string}
 */
function unownedLine(files) {
  const shown = files.slice(0, MAX_SHOWN_PATHS).map((f) => `\`${f}\``).join(", ");
  const more = files.length > MAX_SHOWN_PATHS ? ", …" : "";
  return `- The main tree has ${files.length} uncommitted changed file(s) owned by no task — the serial lane is waiting (${shown}${more}); commit or stash (\`git stash\`), then rerun`;
}

/**
 * Harvest the answers a human typed in the INBOX. PURE FUNCTION.
 * An answer is the text after `ANSWER` plus every following line up to the next heading.
 * @param {string} text @returns {Map<string, string>} Q-id → answer (empty answers dropped)
 */
export function parseAnswers(text) {
  /** @type {Map<string, string>} */
  const answers = new Map();
  /** @type {string|null} */
  let current = null;
  /** @type {string[]|null} */
  let buffer = null;

  const flush = () => {
    if (current !== null && buffer !== null) {
      const value = buffer.join("\n").trim();
      if (value !== "") answers.set(current, value);
    }
    buffer = null;
  };

  for (const line of text.split("\n")) {
    const heading = /^#{2,3}\s+(Q-\d{3})\b/.exec(line);
    if (heading || /^#{1,3}\s/.test(line)) {
      flush();
      current = heading ? heading[1] : null;
      continue;
    }
    if (current !== null && buffer === null && line.startsWith(ANSWER)) {
      buffer = [line.slice(ANSWER.length)];
      continue;
    }
    if (buffer !== null) buffer.push(line);
  }
  flush();
  return answers;
}

/**
 * @template {{id: string, updated: string|null}} T
 * @param {T[]} items @returns {T[]}
 */
function newestFirst(items) {
  return items.sort((a, b) => {
    const ua = a.updated ?? "";
    const ub = b.updated ?? "";
    if (ua !== ub) return ub.localeCompare(ua);
    return a.id.localeCompare(b.id);
  });
}

/**
 * File layer: read the old INBOX to keep unharvested answers, regenerate, overwrite.
 * @param {string} [tasksDir] @param {Conflict[]} [conflicts]
 * @param {import("./ci-status.mjs").CiDeps} [ciDeps]  only for tests to inject a fake `exec` — by default calls the real `gh` (through a 5-minute memo)
 * @returns {{file: string, text: string}}
 */
export function writeInbox(tasksDir = config.tasksDir, conflicts = [], ciDeps = {}) {
  const file = path.join(tasksDir, "INBOX.md");
  const previous = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  const pending = previous === null ? new Map() : parseAnswers(previous);
  const backlog = loadBacklog(tasksDir);
  const root = path.dirname(path.resolve(tasksDir));
  // A `doing` task not owned by a worker (serial lane on the main tree) holds the tree — dirty changes then belong to it.
  const held = [...backlog.values()].some((t) => t.status === "doing" && slotOfOwner(t.owner) === null);
  const gate = ciGateNow(root, config.ci, ciDeps);
  const text = buildInbox({
    backlog,
    unowned: unownedChanges({ dirty: readDirtyTree(root), leftover: readSerialLeftover(), backlog, held }),
    orphans: orphanWorktrees(backlog, listWorktrees(root).map((w) => w.id)),
    bugs: loadBugs(tasksDir),
    questions: loadQuestions(tasksDir),
    conflicts,
    pending,
    findings: loadFindings(root),
    ci: gate.status,
    ciClosed: gate.closed ? { unpushed: gate.unpushed } : null,
  });
  const before = previous === null ? null : inboxCounts(previous);
  fs.writeFileSync(file, text);
  const after = inboxCounts(text);
  // Only when the counts CHANGE (or there is no old INBOX to compare): the INBOX is regenerated every round, not every round is news.
  if (before === null || before.questions !== after.questions || before.approvals !== after.approvals) {
    emitEvent(root, "inbox.changed", after);
  }
  return { file, text };
}

/**
 * Number of open questions and items awaiting approval, read from the INBOX section titles. PURE FUNCTION.
 * @param {string} text @returns {{questions: number, approvals: number}}
 */
export function inboxCounts(text) {
  /** @param {string} title */
  const count = (title) => Number(new RegExp(`^## ${title} \\((\\d+)\\)`, "m").exec(text)?.[1] ?? 0);
  return { questions: count(INBOX_SECTIONS.questions), approvals: count(INBOX_SECTIONS.approvals) };
}
